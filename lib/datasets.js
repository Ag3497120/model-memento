// 4 つ目の視点「データセット」: 個人や研究者が集めた、そのモデルの実際の出力（蒸留用データ）と、
// そのモデルを真似るよう調整された公開モデルを Hugging Face から探す。
// 名前が似ているだけのデータが多いので、カード（README）を読ませて本当にそのモデルの出力かを判定する。
import { complete } from "./backends.js";

const HF = "https://huggingface.co";
const DS = "https://datasets-server.huggingface.co";
const get = async (url, as = "json") => {
  const r = await fetch(url, { signal: AbortSignal.timeout(20000), headers: { "user-agent": "model-memento/0.2" } });
  if (!r.ok) throw new Error(`${r.status} ${url}`);
  return as === "json" ? r.json() : r.text();
};

const JUDGE_SCHEMA = {
  type: "object", additionalProperties: false, required: ["items"],
  properties: {
    items: {
      type: "array",
      items: {
        type: "object", additionalProperties: false,
        required: ["id", "relevant", "confidence", "generator", "reason"],
        properties: {
          id: { type: "string" },
          relevant: { type: "boolean", description: "true only if the assistant/response texts were generated by the target model itself" },
          confidence: { type: "number", description: "0..1" },
          generator: { type: "string", description: "which model generated the responses, per the card" },
          reason: { type: "string", description: "Japanese, one sentence" },
        },
      },
    },
  },
};

// 行をいろいろな形から {prompt, response} にそろえる
export function toPairs(row) {
  const out = [];
  const conv = row.conversations ?? row.messages ?? row.conversation ?? row.chosen;
  if (Array.isArray(conv)) {
    let last = "";
    for (const m of conv) {
      if (!m || typeof m !== "object") continue;
      const role = String(m.from ?? m.role ?? "").toLowerCase();
      const text = m.value ?? m.content ?? m.text ?? "";
      if (typeof text !== "string") continue;
      if (["human", "user", "prompter"].includes(role)) last = text;
      else if (["gpt", "assistant", "model", "bot", "chatgpt", "claude"].includes(role)) out.push({ prompt: last, response: text });
    }
    return out;
  }
  const p = row.instruction ?? row.prompt ?? row.question ?? row.input ?? row.query ?? "";
  const r = row.output ?? row.response ?? row.completion ?? row.answer ?? (typeof row.chosen === "string" ? row.chosen : null);
  if (typeof r === "string") out.push({ prompt: typeof p === "string" ? p : JSON.stringify(p), response: r });
  else if (typeof row.text === "string") out.push({ prompt: "", response: row.text });
  return out;
}

async function sampleRows(id, want = 160) {
  const splits = (await get(`${DS}/splits?dataset=${encodeURIComponent(id)}`)).splits ?? [];
  const sp = splits.find((s) => s.split === "train") ?? splits[0];
  if (!sp) return [];
  const q = (offset) => `${DS}/rows?dataset=${encodeURIComponent(id)}&config=${encodeURIComponent(sp.config)}&split=${encodeURIComponent(sp.split)}&offset=${offset}&length=100`;
  const first = await get(q(0));
  const rows = first.rows.map((r) => ({ idx: r.row_idx, row: r.row }));
  const total = first.num_rows_total ?? rows.length;
  if (total > 300 && rows.length < want) {
    const off = Math.floor(Math.random() * (total - 100));
    rows.push(...(await get(q(off))).rows.map((r) => ({ idx: r.row_idx, row: r.row })));
  }
  return rows.flatMap(({ idx, row }) => toPairs(row).map((p) => ({ ...p, idx })));
}

export async function findDatasets(target, { actor, emit = () => {} }) {
  const terms = [...new Set([target.name, ...(target.aliases ?? [])].map((s) => s.toLowerCase()))].slice(0, 6);
  emit({ type: "dataset_search", terms });
  const cand = new Map();
  const models = new Map();
  for (const t of terms) {
    const [ds, ms] = await Promise.all([
      get(`${HF}/api/datasets?search=${encodeURIComponent(t)}&limit=15&sort=downloads&direction=-1`).catch(() => []),
      get(`${HF}/api/models?search=${encodeURIComponent(t)}&limit=10&sort=downloads&direction=-1`).catch(() => []),
    ]);
    for (const d of ds) if (!cand.has(d.id)) cand.set(d.id, { id: d.id, downloads: d.downloads ?? 0, likes: d.likes ?? 0 });
    for (const m of ms) if (!models.has(m.id)) models.set(m.id, { id: m.id, url: `${HF}/${m.id}`, downloads: m.downloads ?? 0, gguf: (m.tags ?? []).includes("gguf") });
  }
  const top = [...cand.values()].sort((a, b) => b.downloads + b.likes * 50 - (a.downloads + a.likes * 50)).slice(0, 12);
  if (!top.length) return { evidence: [], samples: [], datasets: [], imitators: [] };

  // カードと最初の 1 行を読ませて判定
  const cards = await Promise.all(top.map(async (d) => {
    const card = await get(`${HF}/datasets/${d.id}/raw/main/README.md`, "text").catch(() => "");
    const pairs = await sampleRows(d.id, 1).catch(() => []);
    return { ...d, card: card.slice(0, 2500), example: pairs[0] ? pairs[0].response.slice(0, 400) : null };
  }));
  emit({ type: "dataset_judge", candidates: cards.length });
  const judged = await complete(actor, {
    system: "You vet Hugging Face datasets for provenance. Be strict: names lie; only the card's description of how responses were generated counts.",
    messages: [{ role: "user", content: `Target model: ${target.name} (${target.vendor}).
For each dataset decide whether its assistant/response texts were GENERATED BY THE TARGET MODEL (e.g. distillation data,
logged chats). Translation corpora, human-written data, or data from a different model are not relevant.

${cards.map((c) => `### ${c.id} (downloads ${c.downloads})\nCARD:\n${c.card || "(no card)"}\nFIRST RESPONSE:\n${c.example ?? "(unreadable)"}`).join("\n\n")}` }],
    jsonSchema: JUDGE_SCHEMA,
    effort: "medium",
  });
  const verdicts = (judged.json?.items ?? []).filter((v) => v.relevant && v.confidence >= 0.5).sort((a, b) => b.confidence - a.confidence).slice(0, 3);

  const evidence = [], samples = [], datasets = [];
  for (const v of verdicts) {
    const pairs = await sampleRows(v.id).catch(() => []);
    const good = pairs.filter((p) => p.response && p.response.length > 20);
    datasets.push({ id: v.id, url: `${HF}/datasets/${v.id}`, confidence: v.confidence, generator: v.generator, reason: v.reason, rows: good.length });
    evidence.push({ lens: "dataset", url: `${HF}/datasets/${v.id}`, title: `HF dataset: ${v.id}`, date: null, quote: null, claim: `Contains ${good.length} sampled responses reportedly generated by ${v.generator}. ${v.reason}` });
    for (const p of good) samples.push({ ...p, source: v.id, weight: v.confidence });
    emit({ type: "dataset_rows", id: v.id, rows: good.length });
  }
  // 真似モデル: 一語だけの別名（"opus" など）は無関係なものを拾うので、複数語の名前でだけ照合する
  const specific = terms.filter((t) => /[\s\-_.]/.test(t) || /\d/.test(t));
  const rx = specific.length ? new RegExp(specific.map((t) => t.replace(/[^a-z0-9]+/g, "[^a-z0-9]*")).join("|"), "i") : null;
  const IGNORE = /^(Helsinki-NLP|facebook|google)\//;
  const imitators = rx ? [...models.values()].filter((m) => rx.test(m.id.split("/")[1] ?? m.id) && !IGNORE.test(m.id)).sort((a, b) => b.downloads - a.downloads).slice(0, 8) : [];
  return { evidence, samples, datasets, imitators };
}
